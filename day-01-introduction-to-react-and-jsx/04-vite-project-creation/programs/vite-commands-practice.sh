# Practical: Vite Project Creation Commands Practiced
# Run these commands step-by-step to practice project creation

# Step 1: Create a React application with Vite template
npm create vite@latest my-first-react-app -- --template react

# Step 2: Navigate into the project
cd my-first-react-app

# Step 3: Install all dependencies
npm install

# Step 4: Run local development server
npm run dev

